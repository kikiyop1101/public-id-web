if (KIT_PAGES.length !== KITS.length) throw new Error('os-kit-pages: KITS와 개수가 다름')

export function getKitPage(slug: string): KitPage | undefined {
  return bySlug.get(slug)
}

/** /os 목록 카드 → 상세 페이지 */
export function kitPath(kit: Kit): string {
  const p = KIT_PAGES.find((x) => x.kit === kit)
  return p ? `/os/${p.slug}` : '/os'
}

/** 같은 그룹의 다른 킷 3개 — 자기 다음부터 돌아가며 고른다(페이지마다 다른 킷을 가리키게). 그룹이 작으면 전체에서 채운다 */
export function relatedKits(page: KitPage, n = 3): KitPage[] {
  const same = KIT_PAGES.filter((p) => p.kit.group === page.kit.group)
  const i = same.indexOf(page)
  const picked = [...same.slice(i + 1), ...same.slice(0, i)].slice(0, n)
  if (picked.length < n) {
    const j = KIT_PAGES.indexOf(page)
    const rest = [...KIT_PAGES.slice(j + 1), ...KIT_PAGES.slice(0, j)].filter(
      (p) => p !== page && !picked.includes(p) && p.kit.group !== '패키지',
    )
    picked.push(...rest.slice(0, n - picked.length))
  }
  return picked
}
